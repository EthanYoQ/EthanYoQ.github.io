const languageButtons = [...document.querySelectorAll("[data-lang]")];
const description = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const dictionary = copy[language] || copy.zh;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.title = dictionary.pageTitle;
  description?.setAttribute("content", dictionary.pageDescription);
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });
  languageButtons.forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.lang === language)));
  document.querySelector('[data-contact="zh"]').hidden = language !== "zh";
  document.querySelector('[data-contact="en"]').hidden = language !== "en";
  localStorage.setItem("ethan-site-language", language);
}

languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.lang)));
setLanguage(localStorage.getItem("ethan-site-language") === "en" ? "en" : "zh");

const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const reveals = [...document.querySelectorAll(".reveal")];
if (reduceMotion || !("IntersectionObserver" in window)) {
  reveals.forEach((element) => element.classList.add("is-visible"));
} else {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -8%" });
  reveals.forEach((element) => revealObserver.observe(element));
}

const videos = [...document.querySelectorAll("video[data-autoplay]")];
if (!reduceMotion && "IntersectionObserver" in window) {
  const videoObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting && entry.intersectionRatio > 0.38) entry.target.play().catch(() => {});
      else entry.target.pause();
    });
  }, { threshold: [0, 0.38, 0.7] });
  videos.forEach((video) => videoObserver.observe(video));
}

const progressSections = [...document.querySelectorAll("[data-progress]")];
const progressNumbers = [...document.querySelectorAll(".progress-numbers span")];
const progressFill = document.querySelector(".progress-fill");
const indexItems = [...document.querySelectorAll(".product-index-item")];

function updateProgress() {
  const viewportPoint = window.innerHeight * 0.46;
  let activeIndex = 0;
  progressSections.forEach((section, index) => {
    if (section.getBoundingClientRect().top <= viewportPoint) activeIndex = index;
  });
  progressNumbers.forEach((number, index) => number.classList.toggle("is-active", index === activeIndex));
  if (progressFill) progressFill.style.height = `${(activeIndex / Math.max(progressSections.length - 1, 1)) * 100}%`;
  indexItems.forEach((item, index) => item.classList.toggle("is-active", Math.max(activeIndex - 1, 0) === index));
}

let scrollFrame = null;
function onScroll() {
  if (scrollFrame) return;
  scrollFrame = requestAnimationFrame(() => {
    updateProgress();
    if (!reduceMotion && window.innerWidth > 700) {
      // Keep transform layers on static screenshots only. Chromium can paint a
      // playing video black when one of its ancestors is translated on scroll.
      document.querySelectorAll("[data-parallax]").forEach((element) => {
        const rect = element.getBoundingClientRect();
        const distance = (window.innerHeight * .5) - (rect.top + rect.height * .5);
        const amount = Number(element.dataset.parallax || 0);
        element.style.translate = `0 ${Math.max(-18, Math.min(18, distance * amount))}px`;
      });
    }
    scrollFrame = null;
  });
}

window.addEventListener("scroll", onScroll, { passive: true });
window.addEventListener("resize", onScroll);
updateProgress();
onScroll();
